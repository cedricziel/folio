// Copies the npm dist files into static/ so cargo builds need no Node.
// Run with `npm run vendor` (or `make assets`) after changing dependencies.
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const modules = join(here, "node_modules");
const staticDir = join(here, "..", "static");

const scripts = {
  "turbo.js": "@hotwired/turbo/dist/turbo.es2017-esm.js",
  "stimulus.js": "@hotwired/stimulus/dist/stimulus.js",
  "scalar.js": "@scalar/api-reference/dist/browser/standalone.js",
};

const fonts = [
  { family: "Geist", pkg: "@fontsource-variable/geist", file: "geist" },
  {
    family: "Geist Mono",
    pkg: "@fontsource-variable/geist-mono",
    file: "geist-mono",
  },
];
const subsets = {
  latin:
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
  "latin-ext":
    "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF",
};

rmSync(join(staticDir, "vendor"), { recursive: true, force: true });
rmSync(join(staticDir, "fonts"), { recursive: true, force: true });
mkdirSync(join(staticDir, "vendor"), { recursive: true });
mkdirSync(join(staticDir, "fonts"), { recursive: true });

for (const [name, from] of Object.entries(scripts)) {
  copyFileSync(join(modules, from), join(staticDir, "vendor", name));
}

let css = "/* Generated by web/vendor.mjs. Do not edit. */\n";
for (const { family, pkg, file } of fonts) {
  const available = new Set(readdirSync(join(modules, pkg, "files")));
  for (const [subset, range] of Object.entries(subsets)) {
    const name = `${file}-${subset}-wght-normal.woff2`;
    if (!available.has(name)) throw new Error(`${pkg} has no ${name}`);
    copyFileSync(
      join(modules, pkg, "files", name),
      join(staticDir, "fonts", name),
    );
    css += `@font-face {
  font-family: "${family}";
  font-style: normal;
  font-display: swap;
  font-weight: 100 900;
  src: url("/static/fonts/${name}") format("woff2");
  unicode-range: ${range};
}
`;
  }
}
writeFileSync(join(staticDir, "fonts", "fonts.css"), css);
